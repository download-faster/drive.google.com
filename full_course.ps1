Theo thông tin trên giao diện, bốn khóa có tổng giá niêm yết 12.000.000 đồng. Khi chọn cả bốn, ưu đãi 25% được hiển thị, đưa tổng thanh toán xuống 9.000.000 đồng. Tổng tài nguyên hiển thị gồm 353 bài học, 114 bài kiểm tra, 399 bài chấm AI và 4.672 bài tập thực hành.

